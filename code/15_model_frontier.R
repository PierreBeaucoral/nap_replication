# ==============================================================================
# 15_model_frontier.R
# Frontier of Proposition 2 (when adaptation commitments rise), drawn in
# Figure fig:nap_model_channels, panel (c).
# Paper: Beaucoral, Goujon and Marchand (2026) — Section 3.3 (proof in Appendix B.1)
#
# For a <= 1/2 the ratio of the envelope effect to the composition effect is
#   r(a; sigma_c) = a |(a/(1-a))^(sigma_c-1) - 1| / |sigma_c - 1|,
# with the Cobb-Douglas limit a log((1-a)/a) at sigma_c = 1. Under gross
# substitutes, adaptation commitments rise for every shift with alpha^1 <= 1/2
# whenever eta * rbar(sigma_c) < 1, i.e. below sigma_b = 1 + 1/rbar(sigma_c).
# rbar is the maximum of r over (0, 1/2], found on a fine grid.
#
# Inputs : none (model primitives only; deterministic, no data, no seed)
# Outputs:
#   output/figures/model/nap_frontier_coords.tex   (\NAPFrontierCoords macro,
#                                                    read by the TikZ figure)
#
# Stage 15 of run_all.R; run_all copies output/figures/ into paper/Figures/.
# ==============================================================================

library(here)

dir_out <- here("output", "figures", "model")
dir.create(dir_out, recursive = TRUE, showWarnings = FALSE)

a_grid <- seq(1e-7, 0.5, length.out = 200001)

ratio_r <- function(a, sigma_c) {
  if (abs(sigma_c - 1) < 1e-9) return(a * log((1 - a) / a))
  a * abs((a / (1 - a))^(sigma_c - 1) - 1) / abs(sigma_c - 1)
}

rbar <- function(sigma_c) max(ratio_r(a_grid, sigma_c))

# Closed form at sigma_c = 2: r(a) = a(1-2a)/(1-a), maximum 3 - 2 sqrt(2)
stopifnot(abs(rbar(2) - (3 - 2 * sqrt(2))) < 1e-8)

sigma_c_grid <- round(c(seq(0.20, 0.95, by = 0.05), seq(1.0, 3.0, by = 0.1)), 2)
frontier     <- 1 + 1 / vapply(sigma_c_grid, rbar, numeric(1))

coords <- paste(sprintf("(%.2f,%.4f)", sigma_c_grid, frontier), collapse = " ")
writeLines(
  c("% Generated by code/15_model_frontier.R -- do not edit by hand.",
    "% Frontier sigma_b = 1 + 1/rbar(sigma_c) of Proposition 2.",
    paste0("\\def\\NAPFrontierCoords{", coords, "}")),
  file.path(dir_out, "nap_frontier_coords.tex")
)

at_sigma <- function(s) frontier[which.min(abs(sigma_c_grid - s))]
message(sprintf("Frontier: sigma_b = %.2f at sigma_c = 0.5, %.2f at 1, %.2f at 2.",
                at_sigma(0.5), at_sigma(1), at_sigma(2)))
